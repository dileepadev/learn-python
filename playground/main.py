# Conditional Statements

# If statement
age = 18
if age >= 18:
    print("You are an adult.") # Output: You are an adult.

# If-else statement
age = 16
if age >= 18:
    print("You are an adult.")
else:
    print("You are a minor.") # Output: You are a minor.

# If-elif-else statement
score = 85
if score >= 90:
    print("Grade: A")
elif score >= 80:
    print("Grade: B") # Output: Grade: B
elif score >= 70:
    print("Grade: C")
elif score >= 60:
    print("Grade: D")
else:
    print("Grade: F")