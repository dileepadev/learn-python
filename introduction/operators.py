# Operators


# Arithmetic Operators
# Numbers
a = 11
b = 5
print("Addition:", a + b)           # Output: Addition: 16
print("Subtraction:", a - b)        # Output: Subtraction: 6
print("Multiplication:", a * b)     # Output: Multiplication: 55
print("Division:", a / b)           # Output: Division: 2.2
print("Floor Division:", a // b)    # Output: Floor Division: 2
print("Modulus:", a % b)            # Output: Modulus: 1
print("Exponentiation:", a ** b)    # Output: Exponentiation: 161051

# Strings
str1 = "Hello"
str2 = "World"
print("String Concatenation:", str1 + " " + str2)  # Output: String Concatenation: Hello World
print("String Repetition:", str1 * 3)              # Output: String Repetition: HelloHelloHello

# Comparison Operators
x = 10
y = 20
print("Equal to:", x == y)          # Output: Equal to: False
print("Not equal to:", x != y)      # Output: Not equal to: True
print("Greater than:", x > y)       # Output: Greater than: False
print("Less than:", x < y)          # Output: Less than: True
print("Greater than or equal to:", x >= y)  # Output: Greater than or equal to: False
print("Less than or equal to:", x <= y)     # Output: Less than or equal to: True

# Logical Operators
p = True
q = False
print("Logical AND:", p and q)      # Output: Logical AND: False
print("Logical OR:", p or q)       # Output: Logical OR: True
print("Logical NOT:", not p)       # Output: Logical NOT: False 

# Assignment Operators
c = 10
c += 5  # Equivalent to c = c + 5
print("After += 5:", c)            # Output: After += 5: 15
c -= 3  # Equivalent to c = c - 3
print("After -= 3:", c)            # Output: After -= 3: 12
c *= 2  # Equivalent to c = c * 2
print("After *= 2:", c)            # Output: After *= 2: 24
c /= 4  # Equivalent to c = c / 4
print("After /= 4:", c)            # Output: After /= 4: 6.0
c //= 2  # Equivalent to c = c // 2
print("After //= 2:", c)           # Output: After //= 2: 3.0
c %= 2  # Equivalent to c = c % 2
print("After %= 2:", c)            # Output: After %= 2: 1.0
c **= 3  # Equivalent to c = c ** 3
print("After **= 3:", c)           # Output: After **= 3: 1.0
