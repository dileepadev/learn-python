# Operators


# Arithmetic Operators
# Numbers
a = 11
b = 5
print("Addition:", a + b)           # Output: 16
print("Subtraction:", a - b)        # Output: 6
print("Multiplication:", a * b)     # Output: 55
print("Division:", a / b)           # Output: 2.2
print("Floor Division:", a // b)    # Output: 2
print("Modulus:", a % b)            # Output: 1
print("Exponentiation:", a ** b)    # Output: 161051

# Strings
str1 = "Hello"
str2 = "World"
print("String Concatenation:", str1 + " " + str2)  # Output: "Hello World"
print("String Repetition:", str1 * 3)              # Output: "HelloHelloHello"